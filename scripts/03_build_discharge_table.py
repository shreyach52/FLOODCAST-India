"""STEP 1c: clean every raw CSV into ONE canonical table + data-quality report.

  python scripts/03_build_discharge_table.py
  python scripts/03_build_discharge_table.py --dir data/raw/synthetic --out-dir data/interim_synthetic
  add  --source-unit cfs  if the raw files turn out to be in cubic feet per second.
Outputs (in --out-dir):  discharge_daily.csv.gz, station_coverage.csv
and  reports/data_report.md  (or <out-dir>/data_report.md for custom out-dirs).
"""
import _bootstrap  # noqa: F401
import argparse
from pathlib import Path

import pandas as pd

from floodcast import config
from floodcast.contracts import DATE, STATION, TARGET, UNIT, validate_canonical_df
from floodcast.io_cwc import (canonicalize, eligible_stations, load_column_map,
                              read_raw, station_coverage)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(config.RAW_CWC))
    ap.add_argument("--out-dir", default=str(config.INTERIM))
    ap.add_argument("--map", default=str(config.COLUMN_MAP_PATH))
    ap.add_argument("--source-unit", default="m3s", choices=["m3s", "cfs"])
    ap.add_argument("--min-years", type=float, default=5.0)
    ap.add_argument("--min-coverage", type=float, default=0.5)
    a = ap.parse_args()

    files = sorted(Path(a.dir).glob("*.csv"))
    if not files:
        raise SystemExit(f"No CSV files in {a.dir}.")
    cmap = load_column_map(Path(a.map))
    if cmap is None:
        print("No configs/column_map.json found: guessing the map per file.")

    parts, lines = [], []
    for f in files:
        raw = read_raw(f)
        df, st = canonicalize(raw, cmap, a.source_unit)
        print(f"{f.name}: in={st['rows_in']:,} out={st['rows_out']:,} bad_dates={st['bad_dates']} "
              f"bad_discharge={st['bad_discharge']} negative={st['negative_discharge']} "
              f"dups_merged={st['duplicates_merged']} dates={st['date_parse']}")
        lines.append(f"| {f.name} | {st['rows_in']:,} | {st['rows_out']:,} | {st['bad_dates']} | "
                     f"{st['bad_discharge']} | {st['negative_discharge']} | "
                     f"{st['duplicates_merged']} | {st['date_parse']} |")
        parts.append(df)

    full = pd.concat(parts, ignore_index=True)
    n0 = len(full)
    full = full.groupby([STATION, DATE], as_index=False).agg(
        {**{c: "first" for c in full.columns if c not in (STATION, DATE)}, TARGET: "mean"})
    cross_file_dups = n0 - len(full)
    full = full[[c for c in parts[0].columns]].sort_values([STATION, DATE]).reset_index(drop=True)
    validate_canonical_df(full)

    cov = station_coverage(full)
    keep = eligible_stations(cov, a.min_years, a.min_coverage)

    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    full.to_csv(out / "discharge_daily.csv.gz", index=False)
    cov.to_csv(out / "station_coverage.csv", index=False)

    report_path = (config.REPORTS / "data_report.md") if out == config.INTERIM else out / "data_report.md"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    rep = [
        "# Data report (auto-generated by 03_build_discharge_table.py)", "",
        f"- Canonical unit: **{UNIT}** (source unit given: {a.source_unit})",
        f"- Rows: **{len(full):,}**   Stations: **{full[STATION].nunique():,}**",
        f"- Date range: {full[DATE].min().date()} to {full[DATE].max().date()}",
        f"- Duplicate (station, date) rows merged across files: {cross_file_dups}",
        f"- Stations with >= {a.min_years} years span and >= {a.min_coverage:.0%} daily coverage: "
        f"**{len(keep)}** of {len(cov)}", "",
        "## Coverage summary (per station)",
        "```",
        cov[["n_obs", "span_years", "coverage", "max_missing_days_in_a_row"]].describe().round(3).to_string(),
        "```", "",
        "## Per-file cleaning log", "",
        "| file | rows in | rows out | bad dates | bad discharge | negative | dups merged | date parse |",
        "|---|---|---|---|---|---|---|---|", *lines, "",
        "## How to read this", "",
        "- **coverage** = observed days / days between first and last observation. "
        "Low coverage (e.g. monsoon-only records) means lag/sequence features may not work for that station.",
        "- Decide the modelling branch from this: many stations with high coverage -> sequence + "
        "multi-horizon models are possible; otherwise lean on tabular models.", "",
    ]
    report_path.write_text("\n".join(rep), encoding="utf-8")

    print(f"\nRows {len(full):,} | stations {full[STATION].nunique():,} | eligible {len(keep)}")
    print(f"Wrote {out/'discharge_daily.csv.gz'}, {out/'station_coverage.csv'}, {report_path}")


if __name__ == "__main__":
    main()
